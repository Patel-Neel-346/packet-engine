// PktmonBackend â€” the only machine-specific seam in the prototype.
// Implements the CaptureBackend interface on top of in-box pktmon.
//
// Bundle execution model (one UAC prompt per runBundle call):
//   1. Node writes the ordered CapturePlans into the generated .ps1.
//   2. The elevated script runs every plan sequentially:
//      stop/clean -> filters -> capture start -> write <plan>.capturestarted
//      -> wait for <plan>.trafficdone (the non-elevated Node traffic
//      generator writes it) or deadline -> counters -> stop -> etl2pcap
//      (all + one per component) -> write <plan>.capturedone.
//   3. When all plans are done the script writes _bundle.done and exits,
//      recording its exit code in _bundle.exitcode for the Node side.
// Every step is logged with its real exit code to <bundleId>.log.
//
// Layer:     capture — machine-specific I/O (pktmon bundle scripts)
// Milestone: M2 — batch capture backend (docs/history/milestone-2-report.md)
// Verified:  produced the whole 14-trace scenario corpus (core + ext batches)
// Exports:   PktmonBackend

import fs from "node:fs";
import path from "node:path";
import { runElevatedScript, type ElevatedResult } from "./elevated.ts";
import { runPktmon, pktmonExe, powershellExe } from "./pktmon.ts";
import {
  type CaptureBackend,
  type CaptureBundleResult,
  type ScenarioBundle,
  type CapturePlan,
} from "./backend.ts";

function psString(v: string): string {
  return `'${v.replace(/'/g, "''")}'`;
}

function planLiteral(p: CapturePlan): string {
  const comps = p.comps.kind === "all" ? `@('all')` : `@(${p.comps.ids.join(",")})`;
  const conv = p.convertIds ?? (p.comps.kind === "ids" ? p.comps.ids : []);
  const maxMB = String(p.maxFileMB ?? 64);
  const timeout = String(p.trafficTimeoutSec ?? 75);
  const filters = p.filters
    .map((f) => `@{n=${psString(f.name)};a=@(${f.args.map(psString).join(",")})}`)
    .join(",");
  return `[pscustomobject]@{id=${psString(p.id)};comps=${comps};conv=@(${conv.join(",")});maxMB=${maxMB};timeoutSec=${timeout};filters=@(${filters})}`;
}

/** CaptureBackend over in-box pktmon: writes the ordered CapturePlans into
 * one bundle .ps1, runs it elevated, and reports per-plan results. */
export class PktmonBackend implements CaptureBackend {
  readonly id = "pktmon";

  private readonly outDir: string;
  private readonly scenDir: string;

  constructor(outDir: string, scenDir: string) {
    this.outDir = outDir;
    this.scenDir = scenDir;
  }

  async checkAvailableNonElevated(): Promise<{ ok: boolean; detail: string }> {
    const status = await runPktmon(["status"]);
    if (status.code === 0) {
      return { ok: true, detail: "pktmon reachable without elevation" };
    }
    return {
      ok: false,
      detail: `exit=${status.code} ${(status.stdout.trim() || status.stderr.trim()).slice(0, 120)}`,
    };
  }

  /** Generate the elevated multi-plan bundle script (public for verification). */
  buildBundleScript(bundle: ScenarioBundle): string {
    const L: string[] = [];
    L.push(`# Generated by PktmonBackend for bundle ${bundle.bundleId}.`);
    L.push(`$ErrorActionPreference = 'Continue'`);
    L.push(`$pkt = ${psString(pktmonExe())}`);
    L.push(`$out = ${psString(this.outDir)}`);
    L.push(`$scen = ${psString(this.scenDir)}`);
    L.push(`$LogFile = Join-Path $scen ${psString(`${bundle.bundleId}.log`)}`);
    L.push(`Set-Content -Path $LogFile -Value '=== bundle ${bundle.bundleId} ===' -Encoding ascii`);
    L.push(`function Log($s) { Add-Content -Path $LogFile -Value $s -Encoding ascii }`);
    L.push(
      `function First($t) { $one = ($t -replace '(\\r|\\n)+', ' '); if (-not $one) { return '' }; return $one.Substring(0, [Math]::Min(400, $one.Length)) }`,
    );
    L.push(`$plans = @(`);
    for (const p of bundle.plans) L.push(`  ${planLiteral(p)}`);
    L.push(`)`);
    L.push(`$code = 0`);
    L.push(`foreach ($s in $plans) {`);
    L.push(`  $started = Join-Path $scen ($s.id + '.capturestarted')`);
    L.push(`  $trafficDone = Join-Path $scen ($s.id + '.trafficdone')`);
    L.push(`  $done = Join-Path $scen ($s.id + '.capturedone')`);
    L.push(`  Remove-Item $started,$trafficDone,$done -Force -ErrorAction SilentlyContinue`);
    L.push(`  $filterOk = $true`);
    L.push(`  & $pkt stop 2>&1 | Out-Null; Log ('[STEP stop] code=' + $LASTEXITCODE)`);
    L.push(
      `  & $pkt filter remove 2>&1 | Out-Null; Log ('[STEP filterRemove] code=' + $LASTEXITCODE)`,
    );
    L.push(`  foreach ($f in $s.filters) {`);
    L.push(`    $o = (& $pkt filter add $f.n @($f.a) 2>&1 | Out-String -Width 16384)`);
    L.push(
      `    Log ('[STEP filterAdd ' + $f.n + ' ' + $s.id + '] code=' + $LASTEXITCODE + ' ' + (First $o))`,
    );
    L.push(`    if ($LASTEXITCODE -ne 0) { $filterOk = $false }`);
    L.push(`  }`);
    L.push(`  if (-not $filterOk) {`);
    L.push(`    & $pkt filter remove 2>&1 | Out-Null`);
    L.push(
      `    Log ('[FALLBACK nofilter ' + $s.id + '] filter add failed; proceeding comp-only (M1-proven path)')`,
    );
    L.push(`  }`);
    L.push(`  $compArgs = @($s.comps)`);
    L.push(`  $etl = Join-Path $out ($s.id + '.etl')`);
    L.push(
      `  $o = (& $pkt start --capture --comp @compArgs --pkt-size 0 --log-mode multi-file --file-name $etl --file-size ([int]$s.maxMB) 2>&1 | Out-String -Width 16384)`,
    );
    L.push(`  Log ('[STEP start ' + $s.id + '] code=' + $LASTEXITCODE + ' ' + (First $o))`);
    L.push(`  if ($LASTEXITCODE -ne 0) { $code = $LASTEXITCODE }`);
    L.push(`  Set-Content -Path $started -Value 'started' -Encoding ascii`);
    L.push(`  $deadline = (Get-Date).AddSeconds([int]$s.timeoutSec)`);
    L.push(
      `  while (-not (Test-Path $trafficDone) -and ((Get-Date) -lt $deadline)) { Start-Sleep -Milliseconds 250 }`,
    );
    L.push(`  Log ('[STEP trafficwait ' + $s.id + '] signalSeen=' + (Test-Path $trafficDone))`);
    L.push(`  Start-Sleep -Milliseconds 800`);
    L.push(`  $o = (& $pkt counters 2>&1 | Out-String -Width 16384)`);
    L.push(`  Log ('[STEP counters ' + $s.id + '] code=' + $LASTEXITCODE + ' >>> ' + $o)`);
    L.push(`  $o = (& $pkt stop 2>&1 | Out-String -Width 16384)`);
    L.push(`  Log ('[STEP stopAfter ' + $s.id + '] code=' + $LASTEXITCODE + ' ' + (First $o))`);
    L.push(
      `  Remove-Item (Join-Path $scen ($s.id + '*.pcapng')) -Force -ErrorAction SilentlyContinue`,
    );
    L.push(
      `  $etls = @(Get-ChildItem -Path $out -Filter ($s.id + '*.etl') | Sort-Object Length -Descending)`,
    );
    L.push(
      `  Log ('[STEP etlLocate ' + $s.id + '] ' + (($etls | ForEach-Object { $_.Name + ':' + $_.Length }) -join ';'))`,
    );
    L.push(`  $main = $etls[0]`);
    L.push(`  if ($main -eq $null) {`);
    L.push(`    Log ('[FAIL etlLocate ' + $s.id + '] no ETL produced'); $code = 1`);
    L.push(`    Set-Content -Path $done -Value 'noetl' -Encoding ascii`);
    L.push(`  } else {`);
    L.push(
      `    $o = (& $pkt etl2pcap $main.FullName --out (Join-Path $scen ($s.id + '_all.pcapng')) 2>&1 | Out-String -Width 16384)`,
    );
    L.push(`    Log ('[STEP etl2pcapAll ' + $s.id + '] code=' + $LASTEXITCODE + ' ' + (First $o))`);
    L.push(`    $allFile = Join-Path $scen ($s.id + '_all.pcapng')`);
    L.push(
      `    if (-not (Test-Path $allFile) -or ((Get-Item $allFile).Length -eq 0)) { Log ('[FAIL etl2pcapAll ' + $s.id + '] missing or 0-byte output'); $code = 1 }`,
    );
    L.push(`    $conv = @($s.conv)`);
    L.push(`    foreach ($cid in $conv) {`);
    L.push(`      if ($cid -ne 'all') {`);
    L.push(
      `        $o = (& $pkt etl2pcap $main.FullName --component-id $cid --out (Join-Path $scen ($s.id + '_c' + $cid + '.pcapng')) 2>&1 | Out-String -Width 16384)`,
    );
    L.push(
      `        Log ('[STEP etl2pcapC' + $cid + ' ' + $s.id + '] code=' + $LASTEXITCODE + ' ' + (First $o))`,
    );
    L.push(`      }`);
    L.push(`    }`);
    L.push(`    Set-Content -Path $done -Value 'done' -Encoding ascii`);
    L.push(`  }`);
    L.push(`}`);
    L.push(
      `Set-Content -Path (Join-Path $scen '_bundle.done') -Value ('exit=' + $code) -Encoding ascii`,
    );
    L.push(
      `Set-Content -Path (Join-Path $scen '_bundle.exitcode') -Value ([string]$code) -Encoding ascii`,
    );
    L.push(`exit $code`);
    return L.join("\r\n");
  }

  async runBundle(bundle: ScenarioBundle): Promise<CaptureBundleResult> {
    fs.mkdirSync(this.scenDir, { recursive: true });
    // Defensive: remove ALL scenario signal files left by previous runs, so
    // waitFor() on the non-elevated side can never mistake a stale signal
    // for this bundle's progress (this exact desync happened on the second
    // core run: stale capturedone/trafficdone made Node race ahead).
    for (const f of fs.readdirSync(this.scenDir)) {
      if (
        f.endsWith(".capturestarted") ||
        f.endsWith(".trafficdone") ||
        f.endsWith(".capturedone") ||
        f === "_bundle.done" ||
        f === "_bundle.exitcode"
      ) {
        fs.rmSync(path.join(this.scenDir, f), { force: true });
      }
    }
    fs.writeFileSync(
      path.join(this.scenDir, `${bundle.bundleId}.plans.json`),
      JSON.stringify(bundle.plans, null, 2),
      "utf8",
    );
    const ps1 = path.join(this.scenDir, `${bundle.bundleId}.ps1`);
    fs.writeFileSync(ps1, this.buildBundleScript(bundle), "utf8");
    fs.rmSync(path.join(this.scenDir, "_bundle.done"), { force: true });
    fs.rmSync(path.join(this.scenDir, "_bundle.exitcode"), { force: true });
    const res: ElevatedResult = await runElevatedScript(ps1);
    return {
      exitCode: res.exitCode,
      logFile: res.logFile,
      logContent: res.logContent,
    };
  }
}
